/**
 * Generates docs/MODELS.md from server/models.ts so the table in the docs can
 * never drift from what the code actually asks ComfyUI for.
 * Run with `npm run docs:models` after touching the manifest.
 */
import { writeFileSync } from 'fs';
import { join } from 'path';
import { BUNDLES, bundleGb } from '../server/models.js';
import { LTX25_ENV, LTX25_STOCK, type Ltx25Slot } from '../server/graphs/ltxfiles.js';
import { ROOT } from '../server/config.js';

// Shared files (the edit bundle reuses qwen's encoder, VAE and LoRA) count once.
const total = [...new Map(BUNDLES.flatMap((b) => b.files).map((f) => [`${f.dir}/${f.file}`, f.gb])).values()]
  .reduce((n, gb) => n + gb, 0);
const core = BUNDLES.filter((b) => !b.optional);

const lines: string[] = [
  '<!-- Generated by `npm run docs:models` from server/models.ts. Do not edit by hand. -->',
  '',
  '# Models',
  '',
  'OpenField does not ship model weights. It drives a ComfyUI install that has them,',
  'and its graphs resolve models **by filename** — so a file has to keep the exact',
  'name in the tables below, in the folder shown, or the render fails.',
  '',
  '## Getting them',
  '',
  '```bash',
  'npm run models -- --list          # what you have, what you are missing',
  'npm run models                    # the core install',
  'npm run models -- --only h3       # one bundle',
  'npm run models -- --all           # everything, optional included',
  '```',
  '',
  'The installer needs `COMFY_MODELS_DIR` pointing at your ComfyUI `models/`',
  'folder, and `HF_TOKEN` for the gated repos. Downloads resume, so an',
  'interrupted 21 GB pull does not start over.',
  '',
  `The core install is **${core.map((b) => b.label).join(' + ')}**, about `,
  `**${Math.round(core.reduce((n, b) => n + bundleGb(b), 0))} GB**. Everything here is about ${Math.round(total)} GB.`,
  '',
  '## Bundles',
  '',
];

for (const b of BUNDLES) {
  lines.push(`### ${b.label} \`${b.id}\``);
  lines.push('');
  lines.push(`${b.purpose}`);
  lines.push('');
  lines.push(`- **Size** ${bundleGb(b)} GB${b.optional ? ' · optional' : ' · part of the core install'}`);
  lines.push(`- **License** ${b.license}`);
  if (b.licenseWarning) lines.push(`- > ⚠️ **${b.licenseWarning}**`);
  if (b.nodes?.length) {
    for (const n of b.nodes) lines.push(`- **Custom nodes** [${n.pack}](${n.url}) — provides \`${n.class}\``);
  }
  lines.push('');
  lines.push('| File | Goes in | Size | Source |');
  lines.push('| --- | --- | --- | --- |');
  for (const f of b.files) {
    const src = `[${f.repo}](https://huggingface.co/${f.repo}/blob/main/${f.path})${f.gated ? ' 🔒' : ''}`;
    lines.push(`| \`${f.file}\` | \`models/${f.dir}/\` | ${f.gb} GB | ${src} |`);
  }
  lines.push('');
}

lines.push('🔒 = gated repo. Open the model page, accept the license, then set `HF_TOKEN`.');
lines.push('');

// The four LTX-2.5 slots and their variables come from server/graphs/ltxfiles.ts.
const ltx = BUNDLES.find((b) => b.id === 'ltx25')!;
const dirOf = (file: string) => ltx.files.find((f) => f.file === file)!.dir;
lines.push(
  '## Other LTX-2.5 weights',
  '',
  'Every LTX-2.5 app loads the same four files. Each one can be swapped for another',
  'file, for example a fine-tune or a different quantization of LTX-2.5, by setting',
  'its variable in `.env`:',
  '',
  '| Variable | Replaces | Folder |',
  '| --- | --- | --- |',
  ...(Object.keys(LTX25_STOCK) as Ltx25Slot[]).map(
    (s) => `| \`${LTX25_ENV[s]}\` | \`${LTX25_STOCK[s]}\` | \`models/${dirOf(LTX25_STOCK[s])}/\` |`,
  ),
  '',
  'The value is the name exactly as ComfyUI lists it in that loader. A file in a',
  'subfolder keeps the subfolder, and ComfyUI on Windows writes it with a backslash:',
  '',
  '```',
  'OPENFIELD_LTX25_TRANSFORMER=ltx25\\my-ltx25-finetune-fp8.safetensors',
  '```',
  '',
  'Restart OpenField after a change. Setup and `npm run doctor` then check for the',
  'configured file in place of the stock one, and `npm run models` never downloads',
  'a configured file: put it in the folder yourself. Variables left unset keep the',
  'stock file. The latent upscaler is not configurable.',
  '',
  'Use weights that keep the LTX-2.5 architecture: the graphs, step counts and',
  'IC-LoRAs (Effects, Mirror, Reshoot, Cast, Stage, HDR) are made for the stock',
  'distilled model. A model with LoRAs merged in can behave differently under those',
  'IC-LoRAs; try each app you use. `npm run workflows` always writes the stock names.',
  '',
);

writeFileSync(join(ROOT, 'docs', 'MODELS.md'), lines.join('\n'));
console.log('docs/MODELS.md written');
